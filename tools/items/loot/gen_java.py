"""Writes the loot roster into the game: LootSpecs.java (every roster item's rarity, value, weight, stack, and for
wave-1 food and drink what eating it does and how it spoils), the item names, and the category tags the kit sorts by.

    python3 tools/items/loot/gen_java.py

Items already in the mod (* in the roster) get specs too, so rarity, value and weight cover them, but are not
registered again.
"""
import json
from pathlib import Path

import roster
import wave1

ROOT = Path(__file__).resolve().parents[3]
JAVA = ROOT / 'src/main/java/com/zomboidcraft/loot/items/LootSpecs.java'
RES = ROOT / 'src/main/resources'
NS = 'zomboidcraft'

# roster category -> the kit's Supplies tab (zomboidcraft:category/<tab>)
TABS = {
    'Canned & dry food': 'food', 'Fresh, fridge & freezer': 'food', 'Snacks & sweets': 'food', 'Drinks': 'food',
    'Kitchen & cooking': 'tools', 'Medical': 'medical', 'Hygiene & household': 'household', 'Hand tools': 'tools',
    'Building & materials': 'materials', 'Electrical & electronics': 'electronics', 'Light & fire': 'tools',
    'Outdoors, camping & farm': 'tools', 'Clothing': 'clothing', 'Bags & containers': 'clothing',
    'Books, magazines & papers': 'books', 'Keys, cards & documents': 'keys', 'Valuables & trade goods': 'valuables',
    'Toys, hobbies & personal': 'valuables', 'Vehicle & fuel': 'materials', 'Military & service': 'tools',
    'Junk & scrap': 'materials',
}
RAR = {'C': 'COMMON', 'S': 'SCARCE', 'R': 'RARE', 'P': 'PRIZED', 'G': 'GRAIL'}
# the leftovers food needs, built in wave 1 although they're junk-wave rows
EXTRA_WAVE1 = {'empty_soda_can', 'empty_jar', 'can_opener'}
EXTRA_ROWS = [
    dict(id='empty_soda_can', name='Empty Soda Can', cat='Junk & scrap', group='', rarity='C', value='0', kg='0.02',
         places=[('trash', 3)], exists=False),
    dict(id='empty_jar', name='Empty Jar', cat='Junk & scrap', group='', rarity='C', value='0', kg='0.25',
         places=[('trash', 2), ('pantry', 1)], exists=False),
]


def stack(kg):
    kg = float(kg)
    return 1 if kg >= 3 else 4 if kg >= 1 else 8 if kg >= 0.3 else 16


def rows():
    out = roster.parse() + EXTRA_ROWS
    for r in out:
        r['wave1'] = (r['cat'] in wave1.WAVE1 or r['id'] in EXTRA_WAVE1) and not r['exists']
    return out


def java_row(r):
    rar = r['rarity'].split('-')[0]
    val = int(str(r['value']).split('-')[0])
    food = 'null'
    f = wave1.parse(wave1.FOOD[r['id']]) if r['id'] in wave1.FOOD else None
    if f and (f['hunger'] or f['thirst']):     # coffee grounds, flour, salt: ingredients, not a meal
        left = next((wave1.REMAINDERS[k] for k in f['flags'] if k in wave1.REMAINDERS), None)
        bits = ' | '.join(f'Food.{k.upper()}' for k in ('drink', 'cold', 'raw', 'always', 'can') if k in f['flags']) or '0'
        food = (f'new Food({f["hunger"]}, {f["sat"]}f, {f["thirst"]}f, {f["fresh"]}f, {f["rot"]}f, {bits}, '
                f'{json.dumps(left) if left else "null"}, {wave1.ALCOHOL.get(r["id"], 0)})')
    return (f'        new LootSpec("{r["id"]}", "{TABS[r["cat"]]}", Rarity.{RAR[rar]}, {val}, {float(r["kg"])}, '
            f'{stack(r["kg"])}, {"true" if r["wave1"] else "false"}, {food}),')


def main():
    rs = rows()
    body = '\n'.join(java_row(r) for r in rs)
    JAVA.parent.mkdir(parents=True, exist_ok=True)
    JAVA.write_text(f'''package com.zomboidcraft.loot.items;

import com.zomboidcraft.combat.rolls.Rarity;
import com.zomboidcraft.loot.items.LootSpec.Food;
import java.util.List;

/** Generated by tools/items/loot/gen_java.py from the loot roster (tools/items/loot/roster.py, wave1.py). */
public final class LootSpecs {{
    public static final List<LootSpec> ALL = List.of(
{body.rstrip(",")}
    );

    private LootSpecs() {{
    }}
}}
''')
    lang_path = RES / 'assets/zomboidcraft/lang/en_us.json'
    lang = json.loads(lang_path.read_text())
    for r in rs:
        if r['wave1']:
            lang[f'item.{NS}.{r["id"]}'] = r['name']
    lang_path.write_text(json.dumps(lang, indent=2, ensure_ascii=False) + '\n')
    tags = {}
    for r in rs:
        tags.setdefault(TABS[r['cat']], []).append(f'{NS}:{r["id"]}')
    for tab, ids in tags.items():
        p = RES / f'data/zomboidcraft/tags/item/category/{tab}.json'
        p.parent.mkdir(parents=True, exist_ok=True)
        # only items that exist in the game go in a tag (a missing id fails the tag); later waves add theirs
        live = [i for i, r in zip(ids, [x for x in rs if TABS[x['cat']] == tab]) if r['wave1'] or r['exists']]
        # optional entries: an item another thread owns may not be in this build yet
        p.write_text(json.dumps({'replace': False, 'values': [{'id': i, 'required': False} for i in live]}, indent=2) + '\n')
    print(f'{len(rs)} specs, {sum(r["wave1"] for r in rs)} registered in wave 1')


if __name__ == '__main__':
    main()
