def use_line(row):
    """The full purpose line for a roster row."""
    iid = row['id']
    bits = []
    if iid in wave1.FOOD:
        f = wave1.parse(wave1.FOOD[iid])
        what = 'Drink' if 'drink' in f['flags'] else 'Eat'
        fills = []
        if f['hunger']:
            fills.append(f'hunger {f["hunger"]}')
        if f['thirst'] > 0:
            fills.append(f'thirst {int(f["thirst"])}')
        elif f['thirst'] < 0:
            fills.append(f'makes you thirsty ({int(f["thirst"])})')
        if fills:
            keep = ('keeps for ever' if not f['rot'] else
                    f'stale in {f["fresh"]:g} d, rotten in {f["rot"]:g} d' + (' in a fridge (3x faster out of one)'
                                                                            if 'cold' in f['flags'] else ''))
            bits.append(f'{what}: {", ".join(fills)}; {keep}.')
        if 'can' in f['flags']:
            bits.append('Sealed: open with a can opener (or a kitchen knife or machete, slower); once open it goes off in days.')
    if iid in USES:
        bits.append(USES[iid])
    elif iid in SKILLBOOKS:
        bits.append(f'Skill book: read to multiply {SKILLBOOKS[iid]} XP (volume for each level band, like Zomboid).')
    elif iid in MAGS:
        bits.append(MAGS[iid])
    elif iid in PAPERS:
        bits.append(PAPERS[iid])
    elif not bits and BY_CAT.get(row['cat']):
        bits.append(BY_CAT[row['cat']])
    return ' '.join(bits)
