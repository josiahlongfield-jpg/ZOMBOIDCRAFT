package com.zomboidcraft.world.gen;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.zomboidcraft.ZomboidCraft;
import com.zomboidcraft.world.county.County;
import com.zomboidcraft.world.county.CountyGen;
import com.zomboidcraft.world.county.Place;
import com.zomboidcraft.world.county.PlaceCache;
import com.zomboidcraft.world.county.Terrain;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderLookup;
import net.minecraft.server.level.WorldGenRegion;
import net.minecraft.world.level.LevelHeightAccessor;
import net.minecraft.world.level.NoiseColumn;
import net.minecraft.world.level.StructureManager;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.BiomeManager;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.chunk.ChunkGeneratorStructureState;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.RandomState;
import net.minecraft.world.level.levelgen.blending.Blender;
import net.minecraft.world.level.levelgen.densityfunction.SamplerContext;
import net.minecraft.world.level.levelgen.structure.StructureSet;

/**
 * The ZomboidCraft world type: Kentucky-style county land with its towns, farms, ports and
 * bases, generated by {@link CountyGen} instead of vanilla noise. No caves, ores or vanilla
 * structures; everything above ground comes from the county plan.
 *
 * <p>"plan" picks the county: "grayhaven" is the hand-planned Grayhaven County with its island
 * city (the world preset asks for it, so every new world gets it); a world saved before the
 * plan has no such field and keeps the endless county it was made with, so its new chunks
 * still join up with the old.
 */
public final class CountyChunkGenerator extends ChunkGenerator {
    public static final MapCodec<CountyChunkGenerator> CODEC = RecordCodecBuilder.mapCodec(i -> i.group(
            BiomeSource.CODEC.fieldOf("biome_source").forGetter(g -> g.biomeSource),
            Codec.STRING.optionalFieldOf("plan", "endless").forGetter(g -> g.plan)
    ).apply(i, CountyChunkGenerator::new));

    private static final Map<Long, CountyGen> GENS = new ConcurrentHashMap<>();
    private static volatile County current;
    /** Whether the world being played is the planned county (set when its level starts). */
    private static volatile boolean planned = true;

    private final String plan;

    public CountyChunkGenerator(BiomeSource biomes, String plan) {
        super(biomes);
        this.plan = plan;
    }

    private boolean isPlanned() {
        return plan.equals("grayhaven");
    }

    /** The county of the world being played, for the commands, maps, loot and spawner. */
    public static CountyGen gen(long seed) {
        return gen(seed, planned);
    }

    private static CountyGen gen(long seed, boolean byPlan) {
        long key = seed * 2 + (byPlan ? 1 : 0);
        CountyGen g = GENS.get(key);
        if (g == null) {
            if (GENS.size() > 3) {
                GENS.clear();
            }
            g = GENS.computeIfAbsent(key, k -> new CountyGen(byPlan ? new County(seed) : County.endless(seed), new PlaceCache(10)));
        }
        current = g.county();
        return g;
    }

    /** The county of the world being generated (the biome source has no seed of its own). */
    public static County current() {
        return current;
    }

    @Override
    protected MapCodec<? extends ChunkGenerator> codec() {
        return CODEC;
    }

    @Override
    public ChunkGeneratorStructureState createState(HolderLookup<StructureSet> structureSets, RandomState random, long seed) {
        planned = isPlanned();
        gen(seed, planned);
        ZomboidCraft.LOGGER.info("ZomboidCraft county ({}) for seed {}", plan, seed);
        return super.createState(structureSets, random, seed);
    }

    @Override
    public CompletableFuture<ChunkAccess> buildTerrain(ChunkAccess chunk, Blender blender, RandomState random,
            StructureManager structures, BiomeManager biomes, WorldGenRegion region, Set<Holder<Biome>> possible) {
        CountyGen g = gen(random.seed(), isPlanned());
        ChunkWriter writer = new ChunkWriter(chunk, region);
        try {
            g.generate(chunk.getPos().x(), chunk.getPos().z(), writer);
        } catch (RuntimeException e) {
            // a bug in one place's builder leaves a hole in that chunk; thrown from here, it can
            // leave the chunk unfinished and the server thread waiting on it until the watchdog
            ZomboidCraft.LOGGER.error("Exception generating county chunk {}", chunk.getPos(), e);
        }
        writer.finish();
        return CompletableFuture.completedFuture(chunk);
    }

    @Override
    public void spawnOriginalMobs(WorldGenRegion region) {
    }

    @Override
    public int getGenDepth() {
        return 384;
    }

    @Override
    public int getSeaLevel() {
        return Terrain.WATER;
    }

    @Override
    public int getMinY() {
        return -64;
    }

    private static int ground(County county, int x, int z) {
        List<Place> near = county.placesNear(x, z, x, z, County.SKIRT);
        return (int) Math.floor(county.ground(x, z, near));
    }

    @Override
    public int getBaseHeight(int x, int z, Heightmap.Types type, LevelHeightAccessor level, RandomState random) {
        int g = ground(gen(random.seed(), isPlanned()).county(), x, z);
        boolean fluidCounts = type != Heightmap.Types.OCEAN_FLOOR && type != Heightmap.Types.OCEAN_FLOOR_WG;
        return (fluidCounts ? Math.max(g, Terrain.WATER - 1) : g) + 1;
    }

    @Override
    public NoiseColumn getBaseColumn(int x, int z, LevelHeightAccessor level, RandomState random) {
        int g = ground(gen(random.seed(), isPlanned()).county(), x, z);
        int min = level.getMinY();
        BlockState[] states = new BlockState[level.getHeight()];
        for (int i = 0; i < states.length; i++) {
            int y = min + i;
            states[i] = y <= g ? Blocks.STONE.defaultBlockState() : y < Terrain.WATER ? Blocks.WATER.defaultBlockState()
                    : Blocks.AIR.defaultBlockState();
        }
        return new NoiseColumn(min, states);
    }

    @Override
    public void addDebugScreenInfo(List<String> info, RandomState random, BlockPos pos, SamplerContext context) {
        County county = gen(random.seed(), isPlanned()).county();
        List<Place> near = county.placesNear(pos.getX(), pos.getZ(), pos.getX(), pos.getZ(), 0);
        info.add("ZomboidCraft: " + (near.isEmpty() ? "countryside" : near.get(0).toString()));
    }
}
